// LANGUAGE SWITCHING
const languageSelector = document.getElementById("language");

if (languageSelector) {
  languageSelector.addEventListener("change", function () {
    const selected = this.value;
    const texts = translations[selected] || translations.en;

    document.querySelectorAll("[data-i18n]").forEach(element => {
      const key = element.getAttribute("data-i18n");
      if (texts[key]) {
        element.textContent = texts[key];
      }
    });

    document.documentElement.lang = selected;
    document.documentElement.dir = selected === "ur" ? "rtl" : "ltr";
  });
}

// VOICE RECORDING
const recordBtn = document.getElementById("recordBtn");
const recordStatus = document.getElementById("recordStatus");
const audioPlayback = document.getElementById("audioPlayback");

let mediaRecorder;
let recordedChunks = [];
let recording = false;

if (recordBtn) {
  recordBtn.addEventListener("click", async function () {
    if (!recording) {
      try {
        const stream = await navigator.mediaDevices.getUserMedia({ audio: true });

        recordedChunks = [];
        mediaRecorder = new MediaRecorder(stream);

        mediaRecorder.ondataavailable = function (event) {
          if (event.data.size > 0) {
            recordedChunks.push(event.data);
          }
        };

        mediaRecorder.onstop = function () {
          const blob = new Blob(recordedChunks, { type: "audio/webm" });
          const audioURL = URL.createObjectURL(blob);
          audioPlayback.src = audioURL;
          audioPlayback.hidden = false;
          stream.getTracks().forEach(track => track.stop());
        };

        mediaRecorder.start();
        recording = true;
        recordBtn.textContent = "Stop Recording";
        recordStatus.textContent = "Recording... Speak now.";
      } catch (error) {
        recordStatus.textContent =
          "Microphone permission denied or unavailable. Please allow microphone access.";
      }
    } else {
      mediaRecorder.stop();
      recording = false;
      recordBtn.textContent = "Start Recording";
      recordStatus.textContent = "Recording completed. Play your audio below.";
    }
  });
}

// COMPLAINT FORM
const complaintForm = document.getElementById("complaintForm");
const formMessage = document.getElementById("formMessage");

if (complaintForm) {
  complaintForm.addEventListener("submit", function (event) {
    event.preventDefault();

    const description = document.getElementById("description").value.trim();
    const category = document.getElementById("category").value;
    const consent = document.getElementById("consent").checked;
    const files = document.getElementById("attachments").files;

    if (!description || !category || !consent) {
      formMessage.textContent = "Please complete all required fields.";
      return;
    }

    const fileWarning = files.length > 0
      ? " Note: Your attachments are not uploaded or stored."
      : "";

    formMessage.textContent =
      "Your information was checked in this browser only. " +
      "It has NOT been sent to any authority or stored. " +
      "Please contact an official helpline for actual assistance." +
      fileWarning;

    formMessage.style.color = "#183d70";
  });
}
